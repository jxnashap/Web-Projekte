export function auditAction(action: string): string {
  if (ACTION[action]) return ACTION[action];
  const offer = action.match(/^angebot_(.+)$/);
  if (offer) return `Angebot ${offer[1].replace(/_/g, " ")}`;
  return action.replace(/_/g, " ");
}

